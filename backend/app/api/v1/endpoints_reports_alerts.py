from typing import Optional
from fastapi import APIRouter, HTTPException, Query, status

from app.schemas.report_alert_schema import (
    AcknowledgeAlertRequest,
    AlertItem,
    VerificationReportResponse,
)
from app.services.member3_integration.alert_service import acknowledge_alert, list_alerts
from app.services.member3_integration.evidence_fusion import (
    fuse_evidence_and_generate_report,
    get_report,
    list_reports,
)

router = APIRouter(tags=["Evidence Fusion, Reports & Alerts"])


@router.post("/reports/generate/{media_id}", response_model=VerificationReportResponse)
def generate_verification_report(media_id: str) -> VerificationReportResponse:
    """Execute evidence fusion across all available forensic modules and generate a comprehensive audit report."""
    try:
        report = fuse_evidence_and_generate_report(media_id)
    except FileNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=str(exc)) from exc
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Evidence fusion failed: {str(exc)}",
        ) from exc

    return VerificationReportResponse(**report)


@router.get("/reports/{report_id}", response_model=VerificationReportResponse)
def get_verification_report(report_id: str) -> VerificationReportResponse:
    """Retrieve an existing verification report by report_id."""
    report = get_report(report_id)
    if not report:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Report '{report_id}' not found.")
    return VerificationReportResponse(**report)


@router.get("/reports", response_model=list[VerificationReportResponse])
def get_all_reports(limit: int = Query(50, ge=1, le=100)) -> list[VerificationReportResponse]:
    """List recent verification audit reports."""
    reports = list_reports(limit=limit)
    return [VerificationReportResponse(**r) for r in reports]


@router.get("/alerts", response_model=list[AlertItem])
def get_alerts(
    severity: Optional[str] = Query(None, description="Filter by severity: Low, Medium, High, Critical"),
    acknowledged: Optional[bool] = Query(None, description="Filter by acknowledgment status"),
) -> list[AlertItem]:
    """Retrieve forensic alerts generated by the evidence fusion system."""
    alerts = list_alerts(severity=severity, acknowledged=acknowledged)
    return [AlertItem(**a) for a in alerts]


@router.patch("/alerts/{alert_id}/acknowledge", response_model=AlertItem)
def ack_alert(alert_id: str, payload: Optional[AcknowledgeAlertRequest] = None) -> AlertItem:
    """Acknowledge a forensic alert with optional notes."""
    notes = payload.notes if payload else None
    updated = acknowledge_alert(alert_id, notes=notes)
    if not updated:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Alert '{alert_id}' not found.")
    return AlertItem(**updated)
